import { glob, mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises"
import { createRequire } from "node:module"
import { dirname, join, relative, resolve, sep } from "node:path"

const root = resolve(import.meta.dirname, "..")
const require = createRequire(join(root, "package.json"))
const coreRoot = dirname(require.resolve("core-js/package.json"))
const pureRoot = dirname(require.resolve("core-js-pure/package.json"))
const coreVersion = JSON.parse(await readFile(join(coreRoot, "package.json"), "utf8")).version
const pureVersion = JSON.parse(await readFile(join(pureRoot, "package.json"), "utf8")).version
if (coreVersion !== pureVersion) throw new Error(`core-js ${coreVersion} and core-js-pure ${pureVersion} must use the same version`)

const custom = Object.assign(Object.create(null), {
    chunk: 1,
    nonNullable: 0,
    asNonNullable: 0,
    toShifted: 0,
    toPopped: 0,
    toPushed: 0,
    toUnshifted: 0,
    toExchange: 2,
    toDeduplicated: 1,
    difference: 1,
    intersection: 1,
    union: 1,
    random: 0,
})

const native = ["pop", "shift", "toString", "toLocaleString"]

const statics = ["from", "fromAsync", "of", "isArray", "isTemplateObject"]

const accessors = ["lastIndex", "lastItem"]

const unscopables = new Set([
    "at",
    "copyWithin",
    "entries",
    "fill",
    "find",
    "findIndex",
    "findLast",
    "findLastIndex",
    "flat",
    "flatMap",
    "includes",
    "keys",
    "values",
    "toReversed",
    "toSorted",
    "toSpliced",
    "with",
    "group",
    "groupBy",
    "groupToMap",
    "groupByToMap",
    "filterOut",
    "filterReject",
    "uniqueBy",
    ...Object.keys(custom),
])
const camel = value => value.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase())
const kebab = value => value.replace(/[A-Z]/g, letter => `-${letter.toLowerCase()}`)

const from = (file, path) => {
    const name = relative(dirname(file), join(root, path)).split(sep).join("/")
    return (name.startsWith(".") ? name : `./${name}`) + ".js"
}

const outputs = new Set()

async function output(path, content) {
    const file = join(root, path)
    outputs.add(file)
    await mkdir(dirname(file), { recursive: true })
    let previous

    try {
        previous = await readFile(file, "utf8")
    } catch (error) {
        if (error.code !== "ENOENT") throw error
    }

    if (previous !== content) await writeFile(file, content, "utf8")
}

const profiles = {}

for (const profile of ["es", "stable", "actual", "full"]) {
    const files = (await readdir(join(coreRoot, profile, "array"))).filter(file => file.endsWith(".js") && file !== "index.js").sort()

    const methods = [...new Set([...files.map(file => camel(file.slice(0, -3))), ...native, ...Object.keys(custom)])]

    profiles[profile] = methods

    const globalImports = []

    const pureExports = [],
        virtualExports = []

    for (const name of methods) {
        const filename = kebab(name)
        const purePath = `src/generated/pure/${profile}/${filename}.ts`
        const globalPath = `src/generated/global/${profile}/${filename}.ts`
        const virtualPath = `src/generated/virtual/${profile}/${filename}.ts`
        const globalVirtualPath = `src/generated/global-virtual/${profile}/${filename}.ts`
        let source

        if (name in custom || accessors.includes(name)) source = `import { ${name} as implementation } from "${from(join(root, purePath), "src/custom")}"\n`
        else if (native.includes(name)) source = `const implementation = Function.call.bind(Array.prototype.${name})\n`
        else source = `import implementation from "core-js-pure/${profile}/array/${filename}.js"\n`

        await output(
            purePath,
            `// Generated by scripts/generate.mjs.\nimport type { ArrayFunctions } from "${from(join(root, purePath), "api")}"\n${source}const method = implementation as ArrayFunctions["${name}"]\nexport default method\n`,
        )
        pureExports.push(`export { default as ${name === "with" ? "arrayWith" : name} } from "./${filename}.js"`)

        if (!statics.includes(name)) {
            let body

            if (native.includes(name)) body = `const implementation = Array.prototype.${name}\n`
            else if (name in custom || accessors.includes(name))
                body = `import pure from "${from(join(root, virtualPath), purePath.slice(0, -3))}"\nfunction implementation(this: ArrayLike<any>, ...args: unknown[]) { return Reflect.apply(pure, undefined, [this, ...args]) }\nObject.defineProperty(implementation, "name", { value: "${name}", configurable: true })\nObject.defineProperty(implementation, "length", { value: ${custom[name] ?? 0}, configurable: true })\n`
            else {
                await readFile(join(pureRoot, profile, "array/virtual", `${filename}.js`))
                body = `import implementation from "core-js-pure/${profile}/array/virtual/${filename}.js"\n`
            }

            await output(
                virtualPath,
                `// Generated by scripts/generate.mjs.\nimport type { VirtualMethod } from "${from(join(root, virtualPath), "api")}"\n${body}export default implementation as VirtualMethod<"${name}">\n`,
            )
            virtualExports.push(`export { default as ${name === "with" ? "arrayWith" : name} } from "./${filename}.js"`)
            await output(
                globalVirtualPath,
                `// Generated by scripts/generate.mjs.\nimport "${from(join(root, globalVirtualPath), globalPath.slice(0, -3))}"\nexport { default } from "${from(join(root, globalVirtualPath), virtualPath.slice(0, -3))}"\n`,
            )
        }

        let global = name in custom || native.includes(name) ? "" : `import "core-js/${profile}/array/${filename}.js"\n`
        if (name in custom || native.includes(name))
            global += `import virtual from "${from(join(root, globalPath), virtualPath.slice(0, -3))}"\nimport { installMethod } from "${from(join(root, globalPath), "src/internals/install")}"\ninstallMethod("${name}", virtual, ${name in custom}, ${unscopables.has(name)})\n`
        if (name in custom)
            global += `import type { ArrayExtensions, ReadonlyArrayExtensions } from "${from(join(root, globalPath), "api")}"\ndeclare global { interface Array<T> extends Pick<ArrayExtensions<T>, "${name}"> {} interface ReadonlyArray<T> extends Pick<ReadonlyArrayExtensions<T>, "${name}"> {} }\n`
        global += `export { default } from "${from(join(root, globalPath), purePath.slice(0, -3))}"\n`
        await output(globalPath, `// Generated by scripts/generate.mjs.\n${global}`)
        if (name in custom) globalImports.push(`import "./${filename}.js"`)
    }

    const properties = methods.map(name => `${name === "with" ? '"with"' : name}: ${name === "with" ? "arrayWith" : name}`).join(", ")
    const imports = methods.map(name => `import ${name === "with" ? "arrayWith" : name} from "./${kebab(name)}.js"`).join("\n")
    await output(
        `src/generated/pure/${profile}/index.ts`,
        `// Generated by scripts/generate.mjs.\n${imports}\n${pureExports.join("\n")}\nconst array = { ${properties} }\nexport default array\n`,
    )
    const virtualNames = methods.filter(name => !statics.includes(name))
    const virtualImports = virtualNames.map(name => `import ${name === "with" ? "arrayWith" : name} from "./${kebab(name)}.js"`).join("\n")
    const virtualProperties = virtualNames.map(name => `${name === "with" ? '"with"' : name}: ${name === "with" ? "arrayWith" : name}`).join(", ")
    await output(
        `src/generated/virtual/${profile}/index.ts`,
        `// Generated by scripts/generate.mjs.\n${virtualImports}\n${virtualExports.join("\n")}\nconst array = { ${virtualProperties} }\nexport default array\n`,
    )
    await output(
        `src/generated/global/${profile}/index.ts`,
        `// Generated by scripts/generate.mjs.\n/// <reference path="../../../../types.d.ts" preserve="true" />\nimport "core-js/${profile}/array/index.js"\n${globalImports.join("\n")}\nexport * from "../../pure/${profile}/index.js"\nexport { default } from "../../pure/${profile}/index.js"\n`,
    )
    await output(
        `src/generated/global-virtual/${profile}/index.ts`,
        `// Generated by scripts/generate.mjs.\nimport "../../global/${profile}/index.js"\nexport * from "../../virtual/${profile}/index.js"\nexport { default } from "../../virtual/${profile}/index.js"\n`,
    )
}

const methods = profiles.full

const imports = [],
    calls = []

for (const name of methods) {
    if (accessors.includes(name)) continue
    const identifier = name === "with" ? "arrayWith" : name
    imports.push(`import ${identifier} from "./${statics.includes(name) ? "pure" : "virtual"}/full/${kebab(name)}.js"`)
    calls.push(
        statics.includes(name)
            ? `installStatic("${name}", ${identifier})`
            : `installMethod("${name}", ${identifier}, ${name in custom}, ${unscopables.has(name)})`,
    )
}

await output(
    "src/generated/install.ts",
    `// Generated by scripts/generate.mjs.\nimport { installAccessors, installMethod, installStatic } from "../internals/install.js"\n${imports.join("\n")}\nexport function extendArrayPrototype() {\n${calls.join("\n")}\ninstallAccessors()\n}\n`,
)

// Remove only stale files owned by this generator, so upgrades cannot publish obsolete entries.
const generatedRoot = join(root, "src/generated")

for await (const path of glob("src/generated/**/*.ts", { cwd: root })) {
    const file = resolve(root, path)
    if (!file.startsWith(generatedRoot + sep)) throw new Error(`Unsafe generated path: ${file}`)
    if (!outputs.has(file) && (await readFile(file, "utf8")).startsWith("// Generated by scripts/generate.mjs.")) await rm(file)
}

const manifestPath = join(root, "package.json")
const manifest = JSON.parse(await readFile(manifestPath, "utf8"))
const entry = path => ({ types: `./dist/${path}.d.ts`, import: `./dist/${path}.js`, require: `./dist/${path}.cjs` })

const exports = {
    ".": entry("index"),
    "./types": { types: "./types.d.ts" },
    "./auto": entry("auto"),
    "./pure": entry("generated/pure/full/index"),
    "./pure/*": entry("generated/pure/full/*"),
    "./virtual": entry("generated/virtual/full/index"),
    "./virtual/*": entry("generated/virtual/full/*"),
}

exports["./*"] = entry("generated/global/full/*")

for (const profile of ["es", "stable", "actual", "full", "features"]) {
    const canonical = profile === "features" ? "full" : profile

    for (const [prefix, kind] of [
        ["", "global"],
        ["pure/", "pure"],
    ]) {
        exports[`./${prefix}${profile}`] = entry(`generated/${kind}/${canonical}/index`)
        exports[`./${prefix}${profile}/*`] = entry(`generated/${kind}/${canonical}/*`)
        exports[`./${prefix}${profile}/array`] = entry(`generated/${kind}/${canonical}/index`)
        exports[`./${prefix}${profile}/array/*`] = entry(`generated/${kind}/${canonical}/*`)
    }

    for (const prefix of [`pure/${profile}/virtual`, `pure/${profile}/array/virtual`]) {
        exports[`./${prefix}`] = entry(`generated/virtual/${canonical}/index`)
        exports[`./${prefix}/*`] = entry(`generated/virtual/${canonical}/*`)
    }

    for (const prefix of [`${profile}/virtual`, `${profile}/array/virtual`]) {
        exports[`./${prefix}`] = entry(`generated/global-virtual/${canonical}/index`)
        exports[`./${prefix}/*`] = entry(`generated/global-virtual/${canonical}/*`)
    }
}

for (const [key, value] of Object.entries(exports)) {
    if (key.includes("*")) exports[`${key}.js`] = value
}

manifest.exports = exports
manifest.sideEffects = ["./dist/auto.*", "./dist/generated/global/**", "./dist/generated/global-virtual/**"]
manifest.scripts.prebuild = "node scripts/generate.mjs"
manifest.files = ["dist", "api.d.ts", "types.d.ts"]
manifest.arrayMethods = profiles
const manifestText = JSON.stringify(manifest, null, 4) + "\n"
if ((await readFile(manifestPath, "utf8")) !== manifestText) await writeFile(manifestPath, manifestText)
console.log(`Generated ${methods.length} Array operations across global, pure and virtual entry points.`)
